// The page's scripts are a committed bundle built from TypeScript; the page must be able to load it, and it must
// still hold the behaviour the pages rely on (a rebuilt bundle that lost one would only show up in a browser).
func TestTheScriptBundleIsServedAndHoldsThePagesBehaviour(t *testing.T) {
	app, _ := setup(t)
	res, err := http.Get(app.URL + "/static/app.js")
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if res.StatusCode != 200 || !strings.Contains(res.Header.Get("Content-Type"), "javascript") {
		t.Fatalf("app.js: %d %q", res.StatusCode, res.Header.Get("Content-Type"))
	}
	js := string(b)
	if !strings.HasPrefix(js, "/* Generated by esbuild from internal/web/ts.") {
		t.Errorf("the bundle must say it is generated, so nobody edits it by hand: %.80s", js)
	}
	for _, behaviour := range []string{"htmx:beforeSwap", "tags-on", "EventSource", "handoff:run", "input.invite", "button.copy", "htmx:confirm", "confirm-title"} {
		if !strings.Contains(js, behaviour) {
			t.Errorf("the bundle lost %q", behaviour)
		}
	}
	// the page loads it with a plain script tag from its own address, which the CSP allows
	if _, body := do(t, "GET", app.URL+"/", "sess=alice", nil); !strings.Contains(body, `<script src="static/app.js" defer>`) {
		t.Error("the page does not load static/app.js")
	}
	if res, err := http.Get(app.URL + "/static/app.js.map"); err != nil || res.StatusCode != 200 {
		t.Errorf("the source map should be served for the browser's developer tools: %v", err)
	}
}

// The fonts come from the app itself: the Content-Security-Policy allows no other font source, and nothing may be
// requested from a font service. Every face the stylesheet names must exist, with its licence beside it.
func TestTheFontsAreServedByTheAppItself(t *testing.T) {
	app, _ := setup(t)
	get := func(path string) (int, string, string) {
		res, err := http.Get(app.URL + path)
		if err != nil {
			t.Fatal(err)
		}
		defer res.Body.Close()
		b, _ := io.ReadAll(res.Body)
		return res.StatusCode, res.Header.Get("Content-Type"), string(b)
	}
	if res, err := http.Get(app.URL + "/"); err != nil || !strings.Contains(res.Header.Get("Content-Security-Policy"), "font-src 'self'") {
		t.Fatalf("the policy must allow fonts from the app: %v", err)
	}
	code, _, css := get("/static/app.css")
	if code != 200 {
		t.Fatalf("app.css: %d", code)
	}
	if strings.Contains(css, "http://") || strings.Contains(css, "https://") || strings.Contains(css, "@import") {
		t.Error("the stylesheet must not reach for anything outside the app")
	}
	faces := regexp.MustCompile(`url\((fonts/[a-z0-9-]+\.woff2)\)`).FindAllStringSubmatch(css, -1)
	if len(faces) < 6 {
		t.Fatalf("expected the six font files to be named in the stylesheet, found %d", len(faces))
	}
	for _, f := range faces {
		code, typ, body := get("/static/" + f[1])
		if code != 200 || len(body) < 2000 || !strings.HasPrefix(body, "wOF2") {
			t.Errorf("%s: %d, %d bytes, not a woff2 file", f[1], code, len(body))
		}
		_ = typ
	}
	for _, name := range []string{"bricolage-grotesque", "figtree", "jetbrains-mono"} {
		if code, _, body := get("/static/fonts/LICENSE-" + name + ".txt"); code != 200 || !strings.Contains(body, "SIL Open Font License") {
			t.Errorf("the licence of %s must ship with the font: %d", name, code)
		}
	}
}

// The policy forbids inline styles and scripts, so a page that uses one would silently lose it in a browser.
func TestPagesUseNoInlineStylesOrScripts(t *testing.T) {
	var st *store.Store
	app, _ := setup(t, withClub(t, &st))
	for _, c := range []struct{ name, path, cookie string }{
		{"owner's page", "/", "sess=family"}, {"sender's page", "/", "sess=other"}, {"admin page", "/admin", "sess=admin"}, {"sign-in notice", "/", ""},
	} {
		_, body := do(t, "GET", app.URL+c.path, c.cookie, nil)
		if regexp.MustCompile(`\sstyle="`).MatchString(body) || strings.Contains(body, "<style") {
			t.Errorf("%s uses an inline style, which the Content-Security-Policy blocks", c.name)
		}
		for _, s := range regexp.MustCompile(`<script[^>]*>`).FindAllString(body, -1) {
			// a data block (the messages for the scripts) is not a script: the browser never runs it
			if !strings.Contains(s, "src=") && !strings.Contains(s, `type="application/json"`) {
				t.Errorf("%s has an inline script: %s", c.name, s)
			}
		}
	}
}

func TestTheShellHasTheIconAndAThemeSwitchAndAppliesTheSavedThemeFirst(t *testing.T) {
	app, _ := setup(t)
	_, body := do(t, "GET", app.URL+"/", "sess=alice", nil)
	for _, want := range []string{`<img src="static/favicon.svg"`, `id="theme"`, `aria-pressed="false"`, `<script src="static/theme.js"></script>`} {
		if !strings.Contains(body, want) {
			t.Errorf("the page lacks %q", want)
		}
	}
	// theme.js must run before anything is painted, so it is neither deferred nor loaded after the other scripts
	if strings.Index(body, "static/theme.js") > strings.Index(body, "static/htmx.min.js") || strings.Contains(body, `theme.js" defer`) {
		t.Error("theme.js must be loaded first and without defer")
	}
	res, err := http.Get(app.URL + "/static/theme.js")
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if res.StatusCode != 200 || !strings.Contains(string(b), "handoff-theme") || !strings.Contains(string(b), "Generated by esbuild") {
		t.Errorf("theme.js: %d", res.StatusCode)
	}
}

// The light behind the page drifts for ever, as in the agreed design. It must stay cheap: only `transform` is
// animated (done by the graphics card, no repainting), and reduced motion stops it.
func TestTheBackgroundDriftsCheaplyAndStopsForReducedMotion(t *testing.T) {
	app, _ := setup(t)
	res, err := http.Get(app.URL + "/static/app.css")
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(res.Body)
	res.Body.Close()
	css := string(b)
	for _, name := range []string{"drift-a", "drift-b"} {
		m := regexp.MustCompile(`@keyframes ` + name + ` \{([^}]*\{[^}]*\})\s*\}`).FindStringSubmatch(css)
		if m == nil {
			t.Fatalf("the %s animation is missing", name)
		}
		if !strings.Contains(m[1], "transform: translate3d(") || strings.Count(m[1], ":") != 1 {
			t.Errorf("%s must animate transform and nothing else (anything else is redrawn every frame): %s", name, m[1])
		}
		if !regexp.MustCompile(`animation: ` + name + ` 24s linear infinite alternate`).MatchString(css) {
			t.Errorf("%s must run for ever, slowly, back and forth", name)
		}
	}
	reduced := regexp.MustCompile(`(?s)@media \(prefers-reduced-motion: reduce\) \{(.*?)\n\}`).FindStringSubmatch(css)
	if reduced == nil || !strings.Contains(reduced[1], "animation-iteration-count: 1") || !strings.Contains(reduced[1], "*::before, *::after") {
		t.Error("reduced motion must stop every animation, including the ones on ::before and ::after")
	}
}

// The page can be added to a phone's home screen: a manifest with the app's icon, icons in the sizes phones ask for, and
// nothing cached (there is no service worker, so nothing signed-in is ever kept by the page itself).
func TestThePageCanBeInstalledOnAPhone(t *testing.T) {
	app, _ := setup(t)
	get := func(path string) (int, string, []byte) {
		res, err := http.Get(app.URL + path)
		if err != nil {
			t.Fatal(err)
		}
		defer res.Body.Close()
		b, _ := io.ReadAll(res.Body)
		return res.StatusCode, res.Header.Get("Content-Type"), b
	}
	code, typ, raw := get("/static/manifest.webmanifest")
	if code != 200 || !strings.HasPrefix(typ, "application/manifest+json") {
		t.Fatalf("manifest: %d %q", code, typ)
	}
	var m struct {
		Name, ShortName, StartURL, Scope, Display, BackgroundColor, ThemeColor string
		Icons                                                                  []struct{ Src, Sizes, Type, Purpose string }
	}
	if err := json.Unmarshal([]byte(strings.NewReplacer("short_name", "shortname", "start_url", "starturl", "background_color", "backgroundcolor", "theme_color", "themecolor").Replace(string(raw))), &m); err != nil {
		t.Fatalf("the manifest is not valid JSON: %v", err)
	}
	if m.Name != "Immich Handoff" || m.Display != "standalone" || m.ThemeColor == "" || m.BackgroundColor == "" {
		t.Errorf("manifest basics: %+v", m)
	}
	// start_url and scope are relative to the manifest, so the app works behind a path prefix: the manifest lives one
	// level down (static/), so "../" is the page itself, and the start is inside the scope
	base, _ := url.Parse("https://host.example/handoff/static/manifest.webmanifest")
	start, _ := base.Parse(m.StartURL)
	scope, _ := base.Parse(m.Scope)
	if start.String() != "https://host.example/handoff/" || !strings.HasPrefix(start.String(), scope.String()) {
		t.Errorf("start %s, scope %s: both must resolve to the page under any prefix", start, scope)
	}
	// the sizes phones ask for, each a real PNG of the size it claims, and one that can be cropped to any shape
	var any192, any512, maskable bool
	for _, ic := range m.Icons {
		code, _, b := get("/static/" + ic.Src)
		if code != 200 {
			t.Errorf("icon %s: %d", ic.Src, code)
			continue
		}
		cfg, format, err := image.DecodeConfig(bytes.NewReader(b))
		if err != nil || format != "png" || fmt.Sprintf("%dx%d", cfg.Width, cfg.Height) != ic.Sizes {
			t.Errorf("icon %s must be a %s png: got %v %s %v", ic.Src, ic.Sizes, cfg, format, err)
		}
		any192 = any192 || (ic.Purpose == "any" && ic.Sizes == "192x192")
		any512 = any512 || (ic.Purpose == "any" && ic.Sizes == "512x512")
		maskable = maskable || ic.Purpose == "maskable"
	}
	if !any192 || !any512 || !maskable {
		t.Errorf("icons needed: 192 any %v, 512 any %v, maskable %v", any192, any512, maskable)
	}
	if code, _, b := get("/static/apple-touch-icon.png"); code != 200 {
		t.Errorf("apple-touch-icon: %d", code)
	} else if cfg, _, err := image.DecodeConfig(bytes.NewReader(b)); err != nil || cfg.Width != 180 || cfg.Height != 180 {
		t.Errorf("the iPhone icon must be 180 x 180: %v %v", cfg, err)
	}

	// the page points at it, with the sign-in cookie sent along (behind a login the manifest would otherwise be refused),
	// and the policy allows it
	res, err := http.Get(app.URL + "/")
	if err != nil {
		t.Fatal(err)
	}
	res.Body.Close()
	if !strings.Contains(res.Header.Get("Content-Security-Policy"), "manifest-src 'self'") {
		t.Error("the policy must allow the manifest from the app itself")
	}
	_, page := do(t, "GET", app.URL+"/", "sess=alice", nil)
	for _, want := range []string{`<link rel="manifest" href="static/manifest.webmanifest" crossorigin="use-credentials">`, `<link rel="apple-touch-icon" href="static/apple-touch-icon.png">`,
		`name="theme-color" content="#f5f2fd" media="(prefers-color-scheme: light)"`, `name="theme-color" content="#0d0b20" media="(prefers-color-scheme: dark)"`} {
		if !strings.Contains(page, want) {
			t.Errorf("the page head lacks %s", want)
		}
	}
	// nothing is cached by the page: the only service worker is the one that shows push notifications, receives photos
	// shared from a phone's gallery and finishes the upload queue. Its one fetch handler answers the share address and
	// nothing else; it has no cache, and it is registered for the static folder only, so it never sits between the page and
	// the app.
	_, _, js := get("/static/app.js")
	if n := strings.Count(string(js), "serviceWorker.register"); n != 1 || !strings.Contains(string(js), `"static/sw.js"`) || !strings.Contains(string(js), `scope:"static/"`) {
		t.Errorf("the script must register the push worker, and only it, for the static folder (%d registrations)", n)
	}
	if strings.Contains(string(raw), "serviceworker") && !strings.Contains(string(raw), "manifest") {
		t.Error("the manifest must not name a service worker")
	}
	_, typ, sw := get("/static/sw.js")
	if res, err := http.Get(app.URL + "/static/sw.js"); err != nil || !strings.Contains(typ, "javascript") || !strings.Contains(res.Header.Get("Content-Security-Policy"), "worker-src 'self'") {
		t.Errorf("the worker is served as a script under the page's policy: %q %v", typ, err)
	}
	for _, forbidden := range []string{"caches", "CacheStorage", "importScripts"} {
		if strings.Contains(string(sw), forbidden) {
			t.Errorf("the worker must not keep a cache: it contains %s", forbidden)
		}
	}
	if n := strings.Count(string(sw), `addEventListener("fetch"`); n != 1 || strings.Count(string(sw), "respondWith") != 1 {
		t.Errorf("the worker has exactly one fetch handler, for the share address (%d handlers)", n)
	}
	for _, want := range []string{"push", "notificationclick", "showNotification", `"share"`} {
		if !strings.Contains(string(sw), want) {
			t.Errorf("the worker lacks %q", want)
		}
	}
}
