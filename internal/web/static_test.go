package web_test

import (
	"io"
	"net/http"
	"strings"
	"testing"
)

// The page's scripts are a committed bundle built from TypeScript; the page must be able to load it, and it must
// still hold the behaviour the pages rely on (a rebuilt bundle that lost one would only show up in a browser).
func TestTheScriptBundleIsServedAndHoldsThePagesBehaviour(t *testing.T) {
	app, _ := setup(t)
	res, err := http.Get(app.URL + "/static/app.js")
	if err != nil {
		t.Fatal(err)
	}
	b, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if res.StatusCode != 200 || !strings.Contains(res.Header.Get("Content-Type"), "javascript") {
		t.Fatalf("app.js: %d %q", res.StatusCode, res.Header.Get("Content-Type"))
	}
	js := string(b)
	if !strings.HasPrefix(js, "/* Generated by esbuild from internal/web/ts.") {
		t.Errorf("the bundle must say it is generated, so nobody edits it by hand: %.80s", js)
	}
	for _, behaviour := range []string{"htmx:beforeSwap", "tags-on", "EventSource", "handoff:run", "input.invite", "button.copy"} {
		if !strings.Contains(js, behaviour) {
			t.Errorf("the bundle lost %q", behaviour)
		}
	}
	// the page loads it with a plain script tag from its own address, which the CSP allows
	if _, body := do(t, "GET", app.URL+"/", "sess=alice", nil); !strings.Contains(body, `<script src="static/app.js" defer>`) {
		t.Error("the page does not load static/app.js")
	}
	if res, err := http.Get(app.URL + "/static/app.js.map"); err != nil || res.StatusCode != 200 {
		t.Errorf("the source map should be served for the browser's developer tools: %v", err)
	}
}
